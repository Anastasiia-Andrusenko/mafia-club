import { createHash } from "crypto";
import { query } from "./db";

/** Shape returned to the frontend (and mirrored by public/reviews.json). */
export type Review = {
  id: number;
  name: string;
  comment: string;
  date: string;
};

/** A row of public/reviews.json (`date` is a naive local timestamp). */
export type SeedReview = Review;

// Historical reviews in public/reviews.json carry no timezone; they were
// written in the business's local time.
const SEED_TIME_ZONE = "Europe/Kyiv";

/**
 * Collapses cosmetic differences so trivially re-worded resubmissions are
 * recognised as the same review: Unicode form, case, invisible characters,
 * repeated whitespace (and the trailing ":" the legacy names carry).
 */
export const normalizeForDedupe = (value: string): string =>
  value
    .normalize("NFKC")
    .replace(/[​-‍⁠﻿]/g, "")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/[\s:]+$/, "")
    .trim();

/** Stable identity of a review: sha256 of the normalised name + comment. */
export const reviewDedupeKey = (name: string, comment: string): string =>
  createHash("sha256")
    .update(`${normalizeForDedupe(name)}\u0000${normalizeForDedupe(comment)}`)
    .digest("hex");

/**
 * Idempotent schema setup (safe to run on every deploy / any number of times).
 * `dedupe_key` is UNIQUE, so duplicate protection is enforced by the database
 * itself and stays correct under concurrent submissions.
 */
export async function ensureReviewsSchema(): Promise<void> {
  await query(`
    CREATE TABLE IF NOT EXISTS reviews (
      id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name        VARCHAR(100)  NOT NULL,
      comment     VARCHAR(2000) NOT NULL,
      date        TIMESTAMPTZ   NOT NULL DEFAULT now(),
      dedupe_key  TEXT          NOT NULL
    )`);
  await query(
    "CREATE UNIQUE INDEX IF NOT EXISTS reviews_dedupe_key_uidx ON reviews (dedupe_key)",
  );
  await query(
    "CREATE INDEX IF NOT EXISTS reviews_date_idx ON reviews (date DESC, id DESC)",
  );
}

/**
 * Inserts the historical reviews, keeping their original ids. Re-running is a
 * no-op: rows whose id or content already exist are skipped. Returns how many
 * rows were actually inserted.
 */
export async function seedReviews(reviews: SeedReview[]): Promise<number> {
  let inserted = 0;
  for (const r of reviews) {
    const rows = await query(
      `INSERT INTO reviews (id, name, comment, date, dedupe_key)
       VALUES ($1, $2, $3, ($4::timestamp AT TIME ZONE '${SEED_TIME_ZONE}'), $5)
       ON CONFLICT DO NOTHING
       RETURNING id`,
      [r.id, r.name, r.comment, r.date, reviewDedupeKey(r.name, r.comment)],
    );
    inserted += rows.length;
  }

  // Explicit ids do not advance the identity sequence: move it past the
  // highest id (never backwards) so the next real review gets a fresh id.
  await query(`
    SELECT setval(
      s,
      GREATEST(COALESCE(pg_sequence_last_value(s), 0),
               (SELECT COALESCE(MAX(id), 1) FROM reviews)),
      true
    )
    FROM (SELECT pg_get_serial_sequence('reviews', 'id')::regclass AS s) seq`);

  return inserted;
}

export async function countReviews(): Promise<number> {
  const rows = await query<{ n: number }>(
    "SELECT COUNT(*)::int AS n FROM reviews",
  );
  return rows[0]?.n ?? 0;
}

/** Newest first; `id` breaks ties so the order is fully deterministic. */
export async function listReviews(limit: number): Promise<Review[]> {
  const rows = await query<{
    id: number;
    name: string;
    comment: string;
    date: Date | string;
  }>(
    "SELECT id, name, comment, date FROM reviews ORDER BY date DESC, id DESC LIMIT $1",
    [limit],
  );
  return rows.map((r) => ({
    id: r.id,
    name: r.name,
    comment: r.comment,
    date: new Date(r.date).toISOString(),
  }));
}

/**
 * Publishes a review immediately. Returns "duplicate" (without writing) when
 * an identical review - after normalisation - already exists.
 */
export async function addReview(
  name: string,
  comment: string,
): Promise<"created" | "duplicate"> {
  const rows = await query(
    `INSERT INTO reviews (name, comment, dedupe_key)
     VALUES ($1, $2, $3)
     ON CONFLICT (dedupe_key) DO NOTHING
     RETURNING id`,
    [name, comment, reviewDedupeKey(name, comment)],
  );
  return rows.length > 0 ? "created" : "duplicate";
}
